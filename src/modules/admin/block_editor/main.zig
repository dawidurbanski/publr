    \\body:has(#pbe-shell) main > div { max-width: none !important; padding: 0 !important; margin: 0 !important; flex: 1; display: flex; flex-direction: column; min-height: 0; }
    \\#pbe-shell { flex: 1; min-height: 0; display: flex; flex-direction: column; }
    \\/* No theme bridging needed: the shell is self-skinned — its vendored
    \\   stylesheet scopes the editor's own dark tokens to #editor-shell,
    \\   so the admin's light/dark theme cannot recolor the editor UI
    \\   (same acceptance look as the standalone demo). */
    \\#pbe-shell #editor-shell { flex: 1; min-height: 0; }
    \\/* The adopted sidebar drops its own width/border — the host panel
    \\   provides the frame. (Class list mirrors layout_edit.zsx.) */
    \\[data-host-panel] > div > aside { width: 100% !important; border: 0 !important; }
