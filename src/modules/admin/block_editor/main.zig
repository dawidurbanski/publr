fn blockBootstrap(args: editors.BootstrapArgs, w: AnyWriter) anyerror!void {
    const allocator = args.ctx.allocator;
    const db = if (auth_middleware.auth) |a| a.db else return;

    var entry = (cms.query.getEntry(allocator, db, args.def.type_id, args.entry_id) catch return) orelse return;
    defer entry.deinit(allocator);

    // The markup lives in the ZSX view (epic #191); attribute values are
    // escaped by the ZSX emitter, so the raw field texts pass through as-is.
    try w.writeAll(tpl.render(views.admin.content.block_editor.BlockEditorBootstrap, .{.{
        .type_id = args.def.type_id,
        .entry_id = args.entry_id,
        .entry_status = entry.status,
        .csrf_token = csrf.ensureToken(args.ctx),
        .content = entry.data.getText(CONTENT_FIELD) orelse "",
        .content_editing = entry.data.getText(EDITING_FIELD) orelse "",
        .takeover_css = takeover_css,
        .boot_js = boot_js,
    }}));
}

