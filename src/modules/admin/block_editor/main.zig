//! PublrEditor — the built-in "block" editor (core admin module).
//!
//! Registers `"block"` with the editor registry in `src/editors.zig`.
//! The edit-page interface for a `"block"` content type is PublrEditor's
//! FULL HARNESS (`createEditorShell` from publr-editor/): topbar with
//! undo/redo/inserter/list-view, the block-settings sidebar, patterns
//! explorer — the same builder shell the editor demo runs. The CMS plugs
//! into the shell's host seams:
//!
//!   actions  → a primary Save button in the shell topbar (submits the
//!              standard `content.update` entry form).
//!   panels   → an "Entry" panel (toggled from the shell topbar) that ADOPTS
//!              the admin's server-rendered entry sidebar — publish/discard
//!              buttons (they target `form="entry-form"`, so they keep
//!              working from anywhere in the DOM), version history, and
//!              releases — no re-implementation.
//!
//! Storage: two projections of the same model, mirrored into hidden inputs
//! on every editor commit and saved through the standard `content.update`
//! action:
//!
//!   content          the "data" downcast — clean frontend HTML (data-pb-*
//!                    stripped, settings islands removed, data-p-* kept).
//!                    Themes emit `{entry.content}` directly; no render
//!                    override is needed.
//!   content_editing  the full wire serialization the editor reloads.
//!                    Losing it is non-fatal — the permissive upcast turns
//!                    plain `content` HTML into raw-html blocks — but typed
//!                    editability comes from this field.
//!
//! Both are produced by the editor's own downcast pipelines, so the CMS
//! never re-implements (and never drifts from) the strip semantics.
//!
//! Vendored bundle (2 files) lives in `vendor/` — GENERATED by
//! `scripts/vendor-editor.sh` (parent workspace); never edit in place.
//! Served under `/admin/editors/block/<file>` by the core asset route.
//!
//! Pre-requisites for a content type to use this editor:
//!   .editor = "block"
//!   .fields = &.{ field.Text("content", .{}), field.Text("content_editing", .{}), ... }

